#!/usr/bin/env python3
"""Generate our tiny native interceptor bridge, without vendor stubs or implementation code.

The target Kotlin interface omits checked-exception declarations. A java.lang.reflect.Proxy
would wrap native IOExceptions in UndeclaredThrowableException. This concrete bridge forwards
InvocationHandler.invoke directly, so native throwables retain their original identity.
Only the three public interface/type descriptors are referenced; no vendor classes are bundled.
"""
import argparse
import base64
import os
from pathlib import Path
import struct
import subprocess
import tempfile


def class_file(name='io/github/aicybridge/nativebridge/HttpLogInterceptor', interface_type='bi/N',
               chain_type='bi/M', response_type='bi/h0'):
    pool = []
    ids = {}

    def entry(key, make):
        if key not in ids:
            payload = make()
            ids[key] = len(pool) + 1
            pool.append(payload)
        return ids[key]

    u2 = lambda n: struct.pack('>H', n)
    u4 = lambda n: struct.pack('>I', n)

    def utf(text):
        data = text.encode('utf-8')
        return entry(('utf', text), lambda: b'\x01' + u2(len(data)) + data)

    def cls(name):
        return entry(('class', name), lambda: b'\x07' + u2(utf(name)))

    def name_type(name, desc):
        return entry(('nt', name, desc), lambda: b'\x0c' + u2(utf(name)) + u2(utf(desc)))

    def member(tag, owner, name, desc):
        return entry((tag, owner, name, desc), lambda: bytes([tag]) + u2(cls(owner)) + u2(name_type(name, desc)))

    this_class, parent = cls(name), cls('java/lang/Object')
    interface = cls(interface_type)
    handler_type = 'Ljava/lang/reflect/InvocationHandler;'
    field = member(9, name, 'callback', handler_type)
    init = member(10, 'java/lang/Object', '<init>', '()V')
    invoke = member(11, 'java/lang/reflect/InvocationHandler', 'invoke',
                    '(Ljava/lang/Object;Ljava/lang/reflect/Method;[Ljava/lang/Object;)Ljava/lang/Object;')
    response = cls(response_type)
    code_name = utf('Code')

    def method(flags, method_name, desc, stack, locals_, code):
        body = u2(stack) + u2(locals_) + u4(len(code)) + code + u2(0) + u2(0)
        return u2(flags) + u2(utf(method_name)) + u2(utf(desc)) + u2(1) + u2(code_name) + u4(len(body)) + body

    constructor = b'\x2a\xb7' + u2(init) + b'\x2a\x2b\xb5' + u2(field) + b'\xb1'
    intercept = (b'\x2a\xb4' + u2(field) + b'\x2a\x01\x04\xbd' + u2(parent)
                 + b'\x59\x03\x2b\x53\xb9' + u2(invoke) + b'\x04\x00\xc0' + u2(response) + b'\xb0')
    methods = [method(1, '<init>', '(' + handler_type + ')V', 2, 2, constructor),
               method(17, 'intercept', '(L' + chain_type + ';)L' + response_type + ';', 7, 2, intercept)]
    fields = u2(18) + u2(utf('callback')) + u2(utf(handler_type)) + u2(0)
    return (b'\xca\xfe\xba\xbe' + u2(0) + u2(49) + u2(len(pool) + 1) + b''.join(pool)
            + u2(49) + u2(this_class) + u2(parent) + u2(1) + u2(interface)
            + u2(1) + fields + u2(len(methods)) + b''.join(methods) + u2(0))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk', default=os.environ.get('ANDROID_HOME'))
    parser.add_argument('--build-tools', default='37.0.0')
    parser.add_argument('--output', default='app/src/main/java/io/github/aicybridge/hook/NativeLogBridge.java')
    args = parser.parse_args()
    sdk = Path(args.sdk)
    with tempfile.TemporaryDirectory(prefix='aicy-log-bridge-') as directory:
        root = Path(directory)
        source = root / 'HttpLogInterceptor.class'
        source.write_bytes(class_file())
        destination = root / 'dex'; destination.mkdir()
        d8 = sdk / 'build-tools' / args.build_tools / ('d8.bat' if os.name == 'nt' else 'd8')
        subprocess.run([str(d8), '--min-api', '26', '--lib', str(sdk / 'platforms/android-37.0/android.jar'),
                        '--output', str(destination), str(source)], check=True)
        dex = (destination / 'classes.dex').read_bytes()
    # Inspection is structural and does not load any vendor code.
    from inspect_dex import Dex
    classes = list(Dex(dex).classes(['L']))
    assert len(classes) == 1 and classes[0]['class'] == 'Lio/github/aicybridge/nativebridge/HttpLogInterceptor;'
    encoded = base64.b64encode(dex).decode('ascii')
    output = '''package io.github.aicybridge.hook;

import android.util.Base64;
import dalvik.system.InMemoryDexClassLoader;
import java.lang.ref.WeakReference;
import java.nio.ByteBuffer;
import java.util.WeakHashMap;

/** Generated by tools/generate_log_bridge.py; our concrete bridge preserves native IOExceptions. */
final class NativeLogBridge {
    private NativeLogBridge() { }
    private static final String DEX = "%s";
    private static final WeakHashMap<ClassLoader, WeakReference<Class<?>>> CACHE = new WeakHashMap<>();
    static synchronized Class<?> type(ClassLoader parent) throws ClassNotFoundException {
        WeakReference<Class<?>> cached = CACHE.get(parent);
        Class<?> type = cached == null ? null : cached.get();
        if (type == null) {
            type = new InMemoryDexClassLoader(ByteBuffer.wrap(Base64.decode(DEX, Base64.NO_WRAP)), parent)
                    .loadClass("io.github.aicybridge.nativebridge.HttpLogInterceptor");
            CACHE.put(parent, new WeakReference<>(type));
        }
        return type;
    }
}
''' % encoded
    Path(args.output).write_text(output)
    print('Generated native logger bridge:', len(dex), 'bytes; one module-owned class')


if __name__ == '__main__':
    main()
